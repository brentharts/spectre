#!/usr/bin/python3
"""
spectre_holonomy.py -- the derived normal and the SU(2) connection of the Spectre substitution tree

Built on spectrespace.py (the substitution tree with every placement kept).  Every statement below is a
computation on a finite patch with a check that fails loudly; none of it is a Fact of spectrefacts.py yet.

1. The derived normal.  A placement T of the plane has linear part L in O(2).  An orientation preserving
   extension to R^3 that maps the plane z=0 to itself maps the z axis to +-z, so it is blockdiag(L, e) with
   e = +-1, and det = e*det(L) = 1 forces e = det(L).  The normal of a tile is therefore n = det(L) z, with no
   further choice: it is the parity of the level.

2. The connection.  SO(3) is covered twice by SU(2), so each edge of the tree (parent -> child) gets a unit
   quaternion: a rotation by a about z for a proper placement, a half turn about the mirror axis for a flip.
   The sign of a half turn (+pi or -pi) is the sign of its quaternion.  The node holonomy H is the product of
   the edge quaternions from the root.

   Tests:  (a) the SO(3) image of H is the lifted global frame, for every node and every twist sign;
           (b) the group generated by the edge quaternions is finite: its order and element orders;
           (c) the twist sign only multiplies node holonomies by +-1 (a Z2 gauge transformation);
           (d) a LOCAL rule, which needs only the relative orientation of two neighbouring tiles, assigns a
               rotation about z to every pair of tiles that touch at a vertex.  Going once round a vertex it
               returns +-1 in SU(2): the Z2 flux, (-1)^w with w the winding number of the orientation field.

    python3 spectre_holonomy.py            n=3, checks, writes spectre_holonomy.png
    python3 spectre_holonomy.py -n 4
"""
import argparse
import os
import sys
from collections import Counter, defaultdict

import matplotlib

if "--show" not in sys.argv:
    matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.collections import PolyCollection
from matplotlib.lines import Line2D

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spectrespace as S  # noqa: E402

BLUE, ORANGE, BLACK = "#0072B2", "#D55E00", "#000000"
CHECKS = []


def check(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    print(f"  [{'ok' if ok else 'FAIL'}] {name}" + (f"   {detail}" if detail else ""))


# ---------------------------------------------------------------------------
# quaternions (w, x, y, z); the unit ones are SU(2)
# ---------------------------------------------------------------------------
IDQ = np.array([1.0, 0.0, 0.0, 0.0])


def qmul(a, b):
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    return np.array([w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2,
                     w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
                     w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2,
                     w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2])


def qconj(a):
    return a * np.array([1.0, -1.0, -1.0, -1.0])


def qrot(q):
    """SO(3) image of a unit quaternion."""
    w, x, y, z = q
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                     [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                     [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])


def qz(a):
    return np.array([np.cos(a / 2), 0.0, 0.0, np.sin(a / 2)])


def qkey(q):
    return tuple(np.round(q, 8) + 0.0)


def closure(gens, cap=5000):
    elems = {qkey(IDQ): IDQ}
    frontier = [IDQ]
    while frontier:
        new = []
        for e in frontier:
            for g in gens:
                p = qmul(e, g)
                k = qkey(p)
                if k not in elems:
                    elems[k] = p
                    new.append(p)
                    if len(elems) > cap:
                        return None
        frontier = new
    return list(elems.values())


def element_order(q, cap=200):
    p = q.copy()
    for m in range(1, cap):
        if np.abs(p - IDQ).max() < 1e-9:
            return m
        p = qmul(p, q)
    return None


# ---------------------------------------------------------------------------
# the connection on the tree
# ---------------------------------------------------------------------------
def twist_sign(space, nd, mode):
    par = space.nodes[nd.parent]
    return (-1) ** par.height if mode == "alt" else int(mode)


def edge_quaternion(space, nd, mode):
    L = nd.local[:, :2]
    a = np.arctan2(L[1, 0], L[0, 0])          # in (-pi, pi]
    if S.det2(L) > 0:
        return qz(a)
    phi = a / 2                                 # mirror axis angle
    return twist_sign(space, nd, mode) * np.array([0.0, np.cos(phi), np.sin(phi), 0.0])


def node_holonomies(space, mode):
    eq = {nd.id: edge_quaternion(space, nd, mode) for nd in space.nodes[1:]}
    H = {0: IDQ.copy()}
    for nd in space.nodes[1:]:                  # parents precede children
        H[nd.id] = qmul(H[nd.parent], eq[nd.id])
    return eq, H


# ---------------------------------------------------------------------------
# 1. the derived normal
# ---------------------------------------------------------------------------
def test_normal(space):
    print("\n1. the derived normal  n = det(L) z")
    worst, by_height = 0.0, defaultdict(set)
    for nd in space.nodes:
        n = S.lift3(nd.T[:, :2]) @ np.array([0.0, 0.0, 1.0])
        d = np.sign(S.det2(nd.T[:, :2]))
        worst = max(worst, float(np.abs(n - np.array([0.0, 0.0, d])).max()))
        by_height[nd.height].add(int(round(n[2])))
    check("lifted frame sends z to det(L) z for every node", worst < 1e-12, f"max error {worst:.1e}")

    uniq = True
    for nd in space.nodes[1:]:
        L = nd.local[:, :2]
        good = []
        for e in (1.0, -1.0):
            M = np.zeros((3, 3))
            M[:2, :2] = L
            M[2, 2] = e
            if abs(np.linalg.det(M) - 1.0) < 1e-9:
                good.append(e)
        uniq &= ([int(g) for g in good] == [int(round(S.det2(L)))])
    check("exactly one z-preserving SO(3) extension of each placement, and it has e = det L", uniq)

    parity_ok = all(len(v) == 1 for v in by_height.values())
    check("n_z is constant on each level", parity_ok,
          "  ".join(f"h={h}: {sorted(v)}" for h, v in sorted(by_height.items(), reverse=True)))
    return {h: next(iter(v)) for h, v in by_height.items()}


# ---------------------------------------------------------------------------
# 2. a-c: tree holonomies, the finite group, the gauge character of the twist sign
# ---------------------------------------------------------------------------
def test_tree(space):
    print("\n2. SU(2) holonomies on the substitution tree")
    results = {}
    Hs = {}
    for mode in ("+1", "-1", "alt"):
        eq, H = node_holonomies(space, mode)
        Hs[mode] = H
        worst = max(float(np.abs(qrot(H[nd.id]) - S.lift3(nd.T[:, :2])).max()) for nd in space.nodes)
        check(f"(a) SO(3) image of H equals the lifted global frame, twist sign {mode}", worst < 1e-12,
              f"max error {worst:.1e}")
        gens = {qkey(q): q for q in eq.values()}
        G = closure(list(gens.values()))
        if G is None:
            check(f"(b) edge quaternions generate a finite group, twist sign {mode}", False, "exceeds cap")
            continue
        orders = Counter(element_order(g) for g in G)
        has_m1 = any(np.abs(g - np.array([-1.0, 0, 0, 0])).max() < 1e-9 for g in G)
        results[mode] = (len(G), dict(sorted(orders.items())), has_m1, len(gens))
        check(f"(b) finite group, twist sign {mode}", True,
              f"order {len(G)} from {len(gens)} distinct edge elements; -1 in group: {has_m1}; "
              f"element orders {dict(sorted(orders.items()))}")
    sizes = {v[0] for v in results.values()}
    check("(b) the group does not depend on the twist sign", len(sizes) == 1, f"orders {sorted(sizes)}")

    # (c) the sign only multiplies node holonomies by +-1
    ok = True
    differ = {}
    for a, b in (("+1", "-1"), ("+1", "alt")):
        cnt = 0
        for nd in space.nodes:
            r = qmul(qconj(Hs[a][nd.id]), Hs[b][nd.id])
            if np.abs(r - IDQ).max() < 1e-9:
                continue
            if np.abs(r + IDQ).max() < 1e-9:
                cnt += 1
            else:
                ok = False
        differ[(a, b)] = cnt
    check("(c) changing the twist sign multiplies node holonomies by +-1 only (Z2 gauge)", ok,
          "; ".join(f"{a} vs {b}: {c} of {len(space.nodes)} nodes get -1" for (a, b), c in differ.items()))
    return results, Hs


# ---------------------------------------------------------------------------
# 2d. the local rule and the Z2 flux on vertex stars
# ---------------------------------------------------------------------------
def vertex_stars(space):
    stars = defaultdict(list)
    for li, nd in enumerate(space.leaves()):
        V = nd.verts
        m = len(V)
        area = 0.5 * np.sum(V[:, 0] * np.roll(V[:, 1], -1) - V[:, 1] * np.roll(V[:, 0], -1))
        ccw = area > 0
        for i in range(m):
            v = V[i]
            nx = V[(i + 1) % m] - v
            pv = V[(i - 1) % m] - v
            an, ap = np.arctan2(nx[1], nx[0]), np.arctan2(pv[1], pv[0])
            if ccw:
                start, width = an, (ap - an) % (2 * np.pi)
            else:
                start, width = ap, (an - ap) % (2 * np.pi)
            stars[tuple(np.round(v, 3))].append((li, start % (2 * np.pi), width, tuple(v)))
    return stars


def rel_rotation_deg(LA, LB):
    rel = np.linalg.inv(LA) @ LB
    d = int(round(np.rad2deg(np.arctan2(rel[1, 0], rel[0, 0]))))
    return (180 if d == -180 else d), S.det2(rel)


def test_flux(space, H):
    print("\n3. the local rule and the Z2 flux on vertex stars")
    leaves = space.leaves()
    stars = vertex_stars(space)
    full, rows = 0, []
    skipped = Counter()
    bad_rel = 0
    bad_eps = 0
    for key, wedges in stars.items():
        if abs(sum(w[2] for w in wedges) - 2 * np.pi) > 1e-6:
            skipped["not a full interior vertex"] += 1
            continue
        wedges = sorted(wedges, key=lambda w: w[1])
        k = len(wedges)
        abut = all(abs(((wedges[(i + 1) % k][1] - (wedges[i][1] + wedges[i][2])) + np.pi) % (2 * np.pi) - np.pi) < 1e-6
                   for i in range(k))
        if not abut:
            skipped["wedges do not abut"] += 1
            continue
        full += 1
        P = IDQ.copy()
        total, n_pi = 0, 0
        eps_prod = 1
        for i in range(k):
            A, B = wedges[i][0], wedges[(i + 1) % k][0]
            LA, LB = leaves[A].T[:, :2], leaves[B].T[:, :2]
            d, dr = rel_rotation_deg(LA, LB)
            if dr < 0:
                bad_rel += 1
            q = qz(np.deg2rad(d))
            total += d
            n_pi += abs(d) == 180
            P = qmul(P, q)
            tree = qmul(qconj(H[leaves[A].id]), H[leaves[B].id])   # tree-defined relative element
            if np.abs(tree - q).max() < 1e-9:
                eps_prod *= 1
            elif np.abs(tree + q).max() < 1e-9:
                eps_prod *= -1
            else:
                bad_eps += 1
        flux = 1 if P[0] > 0 else -1
        w = total / 360.0
        rows.append({"pos": np.array(wedges[0][3]), "k": k, "w": int(round(w)), "w_raw": w, "flux": flux,
                     "n_pi": n_pi, "eps": eps_prod, "res": float(np.abs(abs(P[0]) - 1.0)),
                     "labels": tuple(leaves[wd[0]].label for wd in wedges),
                     "angles": tuple(int(round(np.rad2deg(np.arctan2(leaves[wd[0]].T[1, 0], leaves[wd[0]].T[0, 0]))))
                                     for wd in wedges)})
    check("every vertex star found is a closed cycle of abutting tiles", full > 0,
          f"{full} interior vertices; skipped {dict(skipped)}")
    check("neighbouring tiles of a patch differ by a proper rotation (same handedness)", bad_rel == 0)
    check("the local lift and the tree lift agree up to sign on every touching pair", bad_eps == 0)
    check("winding number is an integer and the loop holonomy is +-1",
          all(abs(r["w_raw"] - r["w"]) < 1e-9 and r["res"] < 1e-9 for r in rows))
    check("flux = (-1)^w", all(r["flux"] == (-1) ** (r["w"] % 2) for r in rows))
    check("flux = product of the signs relating the local lift to the tree lift (tree lift is flat)",
          all(r["flux"] == r["eps"] for r in rows))

    fl = Counter(r["flux"] for r in rows)
    wc = Counter(r["w"] for r in rows)
    kc = Counter(r["k"] for r in rows)
    neg = [r for r in rows if r["flux"] == -1]
    neg_safe = [r for r in neg if r["n_pi"] == 0]
    with_pi = [r for r in rows if r["n_pi"] > 0]
    print(f"     valence {dict(sorted(kc.items()))}   winding w {dict(sorted(wc.items()))}   flux {dict(sorted(fl.items()))}")
    print(f"     flux -1 vertices: {len(neg)}; of these with no 180 degree pair (convention independent): {len(neg_safe)}")
    print(f"     vertices with at least one 180 degree pair (flux convention dependent): {len(with_pi)} of {len(rows)}")
    if neg_safe:
        kk = Counter(r["k"] for r in neg_safe)
        ww = Counter(r["w"] for r in neg_safe)
        g2 = sum("Gamma2" in r["labels"] for r in neg_safe)
        g1 = sum("Gamma1" in r["labels"] for r in neg_safe)
        both = sum(("Gamma1" in r["labels"] and "Gamma2" in r["labels"]) for r in neg_safe)
        base_g2 = sum("Gamma2" in r["labels"] for r in rows) / len(rows)
        print(f"     the {len(neg_safe)} convention independent flux -1 vertices: valence {dict(kk)}, w {dict(ww)}; "
              f"touching Gamma2: {g2}, Gamma1: {g1}, both halves of one Mystic: {both}  "
              f"(fraction of all interior vertices touching Gamma2: {base_g2:.2f})")
    return rows


# ---------------------------------------------------------------------------
def figure(space, rows, path, dpi):
    fig, ax = plt.subplots(figsize=(10, 10), constrained_layout=True)
    ax.add_collection(PolyCollection([nd.verts for nd in space.leaves()], facecolors="#EEEEEE",
                                     edgecolors="#999999", linewidths=0.3))
    for r in rows:
        col = ORANGE if r["flux"] == -1 else BLUE
        big = r["flux"] == -1
        hollow = r["n_pi"] > 0
        ax.scatter(*r["pos"], s=46 if big else 12, marker="o",
                   facecolor="none" if hollow else col, edgecolor=col, linewidth=1.2 if hollow else 0.4, zorder=3)
    ax.autoscale_view()
    ax.set_aspect("equal")
    ax.set_xticks([])
    ax.set_yticks([])
    ax.legend(handles=[Line2D([], [], marker="o", ls="", color=ORANGE, label="Z2 flux -1"),
                       Line2D([], [], marker="o", ls="", color=BLUE, markersize=4, label="Z2 flux +1"),
                       Line2D([], [], marker="o", ls="", markerfacecolor="none", markeredgecolor="#444444",
                              label="hollow: a 180 degree pair, sign is a convention")],
              loc="lower left", fontsize=8, framealpha=0.9)
    ax.set_title(f"SU(2) lift of the local orientation rule: Z2 flux at the {len(rows)} interior vertices "
                 f"of the depth-{space.n} patch", fontsize=11)
    fig.savefig(path, dpi=dpi)


def main():
    ap = argparse.ArgumentParser(description="derived normal and SU(2) connection of the substitution tree")
    ap.add_argument("-n", "--iterations", type=int, default=3)
    ap.add_argument("--out", default="spectre_holonomy.png")
    ap.add_argument("--dpi", type=int, default=130)
    ap.add_argument("--show", action="store_true")
    args = ap.parse_args()

    space = S.SpectreSpace(args.iterations)
    ok, n_ref, n_mine, err = S.verify_against_spectre(space)
    check("tree reproduces spectre.py leaf by leaf", ok, f"{n_mine} tiles, max error {err:.1e}")

    test_normal(space)
    results, Hs = test_tree(space)
    rows = test_flux(space, Hs["+1"])

    failed = [n for n, ok in CHECKS if not ok]
    print(f"\n{len(CHECKS) - len(failed)} of {len(CHECKS)} checks pass" + (f"; FAILED: {failed}" if failed else ""))
    fig = figure(space, rows, args.out, args.dpi) if not args.show else None
    if not args.show:
        print(f"wrote {args.out}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
